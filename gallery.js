const galleryIds = ["dps","healing","effects","controls","history","farm","casts","debuffs","selection","uptime"];

function renderGallery(language) {
  const copy = galleryCatalogs[language] || galleryCatalogs.en;
  document.querySelector("#gallery-title").textContent = copy.title;
  document.querySelector("#gallery-intro").textContent = copy.intro;
  galleryIds.forEach((id, index) => {
    const [title, description] = copy.cards[index];
    document.querySelector("#feature-" + id + " h3").textContent = title;
    document.querySelector("#feature-" + id + " .feature-description").textContent = description;
    document.querySelector("#feature-" + id + " img").setAttribute("alt", copy.alt + ": " + title);
    document.querySelector("#feature-" + id + " .expand-label").textContent = copy.open;
  });
}
